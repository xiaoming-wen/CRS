/** 去重后的省份列表（安徽省已在数据源中排第一） */
export const PROVINCE_OPTIONS = CHINA_SCHOOLS_BY_PROVINCE.map(item => item.province)

const schoolsByProvinceMap = CHINA_SCHOOLS_BY_PROVINCE.reduce((acc, item) => {
  const unique = [...new Set(item.schools)]
  acc[item.province] = unique
  return acc
}, {})

export function getSchoolsByProvince (province) {
  if (!province) return []
  return schoolsByProvinceMap[province] ? schoolsByProvinceMap[province].slice() : []
}

/** 按关键字过滤当前省份学校（包含匹配，不限前缀） */
export function filterSchoolsByKeyword (province, keyword, limit = 80) {
  const schools = getSchoolsByProvince(province)
  const k = (keyword || '').trim()
  if (!k) return []
  return schools.filter(name => name.includes(k)).slice(0, limit)
}

export function isSchoolInProvince (province, schoolName) {
  const name = (schoolName || '').trim()
  if (!name) return false
  return getSchoolsByProvince(province).includes(name)
}

